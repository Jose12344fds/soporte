CREATE TABLE IF NOT EXISTS `mantenimientos_ot_costos` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `ot_docentry` INT UNSIGNED NOT NULL,
  `tipo` VARCHAR(12) NOT NULL COMMENT 'REPUESTO o SERVICIO',
  `descripcion` VARCHAR(500) NOT NULL,
  `cantidad` DECIMAL(14,3) NOT NULL DEFAULT 1.000,
  `precio_unitario` DECIMAL(16,2) NOT NULL DEFAULT 0.00,
  `moneda` CHAR(3) NOT NULL DEFAULT 'PEN',
  `codigo_compra_sap` VARCHAR(50) NULL,
  `proveedor` VARCHAR(150) NULL,
  `nombre_original` VARCHAR(255) NOT NULL,
  `nombre_archivo` VARCHAR(255) NOT NULL,
  `ruta_relativa` VARCHAR(500) NOT NULL COMMENT 'Estructura: YYYY/MM/ot_DocEntry/archivo',
  `mime_type` VARCHAR(100) NOT NULL DEFAULT 'application/pdf',
  `tamano_bytes` BIGINT UNSIGNED NOT NULL,
  `user_id` INT(11) UNSIGNED NULL,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_ot_costo_archivo` (`nombre_archivo`),
  KEY `idx_ot_costo_docentry` (`ot_docentry`, `tipo`, `created_at`),
  KEY `idx_ot_costo_codigo_sap` (`codigo_compra_sap`),
  KEY `idx_ot_costo_user` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
